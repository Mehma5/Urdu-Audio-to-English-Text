import librosa
import numpy as np
import torch
import re

def transcribe_urdu_audio(audio_path):
    audio, sr = librosa.load(
        str(audio_path),
        sr=16000,
        mono=True
    )

    if len(audio) == 0:
        raise ValueError("The uploaded audio file is empty.")

    # Use 25-second segments with a small overlap.
    chunk_seconds = 25
    overlap_seconds = 2
    chunk_samples = chunk_seconds * 16000
    overlap_samples = overlap_seconds * 16000
    step = chunk_samples - overlap_samples

    transcripts = []

    for start in range(0, len(audio), step):
        chunk = audio[start:start + chunk_samples]

        if len(chunk) < 16000:
            if np.max(np.abs(chunk), initial=0) < 1e-5:
                continue

        inputs = processor(
            chunk,
            sampling_rate=16000,
            return_tensors="pt"
        )

        inputs = {
            k: v.to(device)
            for k, v in inputs.items()
        }

        if "input_features" in inputs:
            inputs["input_features"] = inputs["input_features"].to(dtype)

        with torch.inference_mode():
            ids = asr_model.generate(
                **inputs,
                language="urdu",
                task="transcribe",
                num_beams=5
            )

        text = processor.batch_decode(
            ids,
            skip_special_tokens=True
        )[0].strip()

        if text:
            transcripts.append(text)

    return " ".join(transcripts).strip()


def translate_urdu_to_english(urdu_text):
    if not urdu_text or not urdu_text.strip():
        raise ValueError("No Urdu text was provided.")

    # Split long transcripts into sentence-sized groups.
    sentences = re.split(r'(?<=[۔.!?؟])\s+', urdu_text.strip())
    chunks = []
    current = ""

    for sentence in sentences:
        if not sentence.strip():
            continue

        candidate = f"{current} {sentence}".strip()

        token_count = len(
            tokenizer(
                candidate,
                add_special_tokens=True,
                truncation=False
            )["input_ids"]
        )

        if token_count > 350 and current:
            chunks.append(current)
            current = sentence
        else:
            current = candidate

    if current:
        chunks.append(current)

    translations = []

    for chunk in chunks:
        inputs = tokenizer(
            chunk,
            return_tensors="pt",
            truncation=True,
            max_length=512
        )

        inputs = {
            k: v.to(device)
            for k, v in inputs.items()
        }

        with torch.inference_mode():
            ids = translation_model.generate(
                **inputs,
                forced_bos_token_id=ENGLISH_TOKEN_ID,
                num_beams=5,
                max_new_tokens=256
            )

        translated = tokenizer.batch_decode(
            ids,
            skip_special_tokens=True
        )[0].strip()

        translations.append(translated)

    return " ".join(translations).strip()


def process_urdu_audio(audio_path):
    urdu_text = transcribe_urdu_audio(audio_path)

    if not urdu_text:
        return {
            "urdu_transcription": "",
            "english_translation": "",
            "status": "No speech could be transcribed."
        }

    english_text = translate_urdu_to_english(urdu_text)

    return {
        "urdu_transcription": urdu_text,
        "english_translation": english_text,
        "status": "Processing completed. Please review for accuracy."
    }

